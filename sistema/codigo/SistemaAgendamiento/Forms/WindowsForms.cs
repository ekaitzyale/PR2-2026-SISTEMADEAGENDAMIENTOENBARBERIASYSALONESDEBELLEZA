 *
 * INFORMACION RECOPILADA DEL REPOSITORIO
 *
 * 1. TECNOLOGIA Y ENTORNO
 * - Interfaz de escritorio desarrollada con C# y Windows Forms.
 * - El proyecto utiliza .NET Framework 4.8.
 * - El proyecto referencia System.Windows.Forms y System.Drawing.
 * - El entorno de desarrollo documentado es Visual Studio 2022.
 *
 * 2. OBJETIVO DE LA INTERFAZ
 * Facilitar al personal de barberias y salones de belleza la gestion
 * de clientes, profesionales, servicios y citas desde una aplicacion
 * de escritorio.
 *
 * 3. MODULOS DE INTERFAZ PREVISTOS EN LOS DOCUMENTOS
 * - Clientes: registrar, consultar, buscar y modificar clientes.
 * - Profesionales: registrar y consultar profesionales.
 * - Servicios: registrar y consultar servicios, duracion y precio.
 * - Citas y agenda: registrar, consultar, modificar y cancelar citas;
 *   mostrar la agenda por fecha y profesional.
 * - Validaciones visuales: informar datos obligatorios, fechas invalidas
 *   y errores de guardado.
 *
 * NOTA: Estos modulos describen el alcance previsto en la documentacion.
 * No significa que todas esas pantallas o funciones ya esten implementadas.
 *
 * 4. RESPONSABILIDAD DEL EQUIPO
 * La documentacion asigna a Leonor Alejandra Almanza Arroyo la interfaz,
 * los formularios, la navegacion y las validaciones visuales.
 * La integracion y las decisiones de alcance son responsabilidad compartida.
 *
 * 5. ELEMENTOS DE WINDOWS FORMS QUE YA EXISTEN
 * - Program.cs configura los estilos visuales y abre Forms.FrmMenu.
 * - Forms/FrmMenu.cs contiene el formulario principal FrmMenu.
 * - FrmMenu muestra el titulo del sistema y el subtitulo del negocio.
 * - Incluye botones para Clientes, Profesionales, Servicios y Citas y agenda.
 * - Los botones estan deshabilitados actualmente; son una estructura inicial.
 * - El formulario usa controles Label y Button, ademas de propiedades
 *   como StartPosition, Size, MinimumSize y BackColor.
 *
 * 6. ARCHIVOS RELACIONADOS
 * - Program.cs: punto de entrada de la aplicacion.
 * - Forms/FrmMenu.cs: menu principal existente.
 * - SistemaAgendamiento.csproj: registra los archivos fuente y las
 *   referencias necesarias para Windows Forms.
 *
 * Este archivo recopila contexto y no implementa pantallas ni funciones.
 * El formulario principal existente se mantiene en FrmMenu.cs para evitar
 * duplicar la clase FrmMenu o alterar el comportamiento del proyecto.
